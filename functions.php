/**
 * Sanitize a gallery field while keeping the editor-friendly one-URL-per-line
 * format used by the project and property editors.
 *
 * @param mixed $value Raw gallery value.
 * @return string
 */
function rivross_sanitize_gallery_urls( $value ) {
	$lines = preg_split( '/\r\n|\r|\n/', (string) $value );
	$urls  = array();
	foreach ( $lines as $line ) {
		$url = esc_url_raw( trim( $line ) );
		if ( '' !== $url && preg_match( '#^(?:https?:)?//#i', $url ) ) {
			$urls[] = $url;
		}
	}
	return implode( "\n", array_values( array_unique( $urls ) ) );
}

/**
 * Keep date fields in the ISO format used by native date inputs and queries.
 *
 * @param mixed $value Raw date value.
 * @return string
 */
function rivross_sanitize_date_value( $value ) {
	$value = sanitize_text_field( (string) $value );
	if ( ! preg_match( '/^\d{4}-\d{2}-\d{2}$/', $value ) ) {
		return '';
	}
	$parts = array_map( 'intval', explode( '-', $value ) );
	return checkdate( $parts[1], $parts[2], $parts[0] ) ? $value : '';
}

