/**
 * Establish the two external font connections before the stylesheet request.
 * This shortens the connection setup time without changing the font stack.
 *
 * @param array  $urls          Existing resource hints.
 * @param string $relation_type Hint relation being rendered.
 * @return array
 */
function rivross_resource_hints( $urls, $relation_type ) {
	if ( 'preconnect' !== $relation_type ) {
		return $urls;
	}

	$urls[] = 'https://fonts.googleapis.com';
	$urls[] = array(
		'href'        => 'https://fonts.gstatic.com',
		'crossorigin' => 'anonymous',
	);

	return $urls;
}
add_filter( 'wp_resource_hints', 'rivross_resource_hints', 10, 2 );

/**
 * Add safe browser hints to images generated by WordPress.
 *
 * Theme templates can still opt a critical image out of lazy loading with an
 * explicit loading attribute. This filter only fills in missing attributes,
 * so it remains friendly to optimization and image CDN plugins.
 *
 * @param array        $attr       Image attributes.
 * @param WP_Post|null $attachment Attachment post.
 * @param string|array $size       Requested image size.
 * @return array
 */
function rivross_image_performance_attributes( $attr, $attachment, $size ) {
	if ( ! array_key_exists( 'decoding', $attr ) || '' === $attr['decoding'] ) {
		$attr['decoding'] = 'async';
	}
	if ( ! array_key_exists( 'loading', $attr ) || '' === $attr['loading'] ) {
		$attr['loading'] = 'lazy';
	}
	return $attr;
}
add_filter( 'wp_get_attachment_image_attributes', 'rivross_image_performance_attributes', 10, 3 );

/**
 * Load the shared Media Library picker on every RIVROSS content editor that
 * exposes a custom image or gallery field. The picker also includes the
 * normal WordPress upload flow, so editors never need to paste image URLs.
 */
function rivross_cpt_media_admin_assets( $hook ) {
	if ( ! in_array( $hook, array( 'post.php', 'post-new.php' ), true ) ) {
		return;
	}
	$screen = get_current_screen();
	$post_types = array( 'rivross_hero_slide', 'rivross_property', 'rivross_project', 'rivross_event', 'rivross_job', 'rivross_leader' );
	if ( ! $screen || ! in_array( $screen->post_type, $post_types, true ) ) {
		return;
	}
	wp_enqueue_media();
	$script = get_template_directory() . '/assets/js/cpt-media-picker.js';
	wp_enqueue_script(
		'rivross-cpt-media-picker',
		get_template_directory_uri() . '/assets/js/cpt-media-picker.js',
		array( 'jquery' ),
		file_exists( $script ) ? filemtime( $script ) : RIVROSS_THEME_VERSION,
		true
	);
}
