/**
 * Group the three business pages beneath Our Companies in a saved WordPress menu.
 *
 * @param array    $items Menu items.
 * @param stdClass $args  Menu arguments.
 * @return array
 */
function rivross_prepare_companies_submenu( $items, $args ) {
	if ( empty( $args->theme_location ) || 'primary' !== $args->theme_location || empty( $items ) ) {
		return $items;
	}

	$parent       = null;
	$parent_index = null;
	$matches      = array( 'real-estate' => null, 'travel-tourism' => null, 'tea-business' => null );
	$labels       = array(
		'real-estate'    => __( 'Real Estate', 'rivross-corporate' ),
		'travel-tourism' => __( 'Travel & Tourism', 'rivross-corporate' ),
		'tea-business'   => __( 'Tea Business', 'rivross-corporate' ),
	);
	$urls = array(
		'real-estate'    => home_url( '/real-estate/' ),
		'travel-tourism' => home_url( '/travel-tourism/' ),
		'tea-business'   => home_url( '/tea-business/' ),
	);

	foreach ( $items as $index => $item ) {
		$title = strtolower( trim( wp_strip_all_tags( (string) $item->title ) ) );
		$url   = strtolower( (string) $item->url );
		if ( null === $parent && ( 'our companies' === $title || false !== strpos( $url, '/our-companies/' ) ) ) {
			$parent       = $item;
			$parent_index = $index;
		}
		foreach ( array_keys( $matches ) as $key ) {
			if ( null === $matches[ $key ] && ( false !== strpos( $url, '/' . $key . '/' ) || $title === strtolower( $labels[ $key ] ) ) ) {
				$matches[ $key ] = $item;
			}
		}
	}

	if ( ! $parent ) {
		return $items;
	}

	$parent_id = (int) $parent->ID;
	$children  = array();
	$used_ids  = array();
	$child_num = 0;
	foreach ( $matches as $key => $matched ) {
		$child = $matched ? $matched : clone $parent;
		if ( ! $matched ) {
			$child_num++;
			$child->ID              = -1000 - $child_num;
			$child->db_id           = $child->ID;
			$child->object_id       = 0;
			$child->object          = 'custom';
			$child->type            = 'custom';
			$child->type_label      = __( 'Custom Link', 'rivross-corporate' );
			$child->menu_order      = $parent->menu_order + $child_num;
			$child->classes         = array( 'menu-item' );
			$child->current         = false;
			$child->current_item_ancestor = false;
			$child->current_item_parent   = false;
		}
		$child->title              = $labels[ $key ];
		$child->url                = $urls[ $key ];
		$child->menu_item_parent   = (string) $parent_id;
		$child->classes            = is_array( $child->classes ) ? array_values( array_diff( $child->classes, array( 'menu-item-has-children', 'current-menu-ancestor', 'current-menu-parent' ) ) ) : array( 'menu-item' );
		$child->classes[]          = 'menu-item-company-link';
		$is_current                = ( is_page( $key ) || ( 'real-estate' === $key && is_singular( 'rivross_property' ) ) );
		$child->current            = $is_current;
		if ( $is_current && ! in_array( 'current-menu-item', $child->classes, true ) ) {
			$child->classes[] = 'current-menu-item';
		}
		$children[] = $child;
		$used_ids[ (string) $child->ID ] = true;
	}

	$parent->classes = is_array( $parent->classes ) ? $parent->classes : array( 'menu-item' );
	if ( ! in_array( 'menu-item-has-children', $parent->classes, true ) ) {
		$parent->classes[] = 'menu-item-has-children';
	}
	if ( array_filter( $children, static function ( $child ) { return ! empty( $child->current ); } ) && ! in_array( 'current-menu-ancestor', $parent->classes, true ) ) {
		$parent->classes[] = 'current-menu-ancestor';
	}

	$updated = array();
	foreach ( $items as $index => $item ) {
		if ( $index === $parent_index ) {
			$updated[] = $parent;
			foreach ( $children as $child ) {
				$updated[] = $child;
			}
			continue;
		}
		if ( isset( $used_ids[ (string) $item->ID ] ) ) {
			continue;
		}
		$updated[] = $item;
	}

	return $updated;
}
add_filter( 'wp_nav_menu_objects', 'rivross_prepare_companies_submenu', 6, 2 );

/**
 * Keep the dedicated property portal discoverable when an older saved menu
 * does not yet contain the Real Estate item.
 *
 * @param string   $items Menu HTML.
 * @param stdClass $args  Menu arguments.
 * @return string
 */
function rivross_add_real_estate_menu_item( $items, $args ) {
	if ( empty( $args->theme_location ) || 'primary' !== $args->theme_location || false !== strpos( $items, '/real-estate/' ) ) {
		return $items;
	}
	$current = ( is_page( 'real-estate' ) || is_singular( 'rivross_property' ) ) ? ' current-menu-item' : '';
