/**
 * Resolve a Customizer link while keeping local section anchors on the site.
 *
 * @param string $url URL or a local #anchor.
 * @return string
 */
function rivross_theme_link( $url ) {
	$url = trim( (string) $url );
	if ( '' === $url ) {
		return '#';
	}
	/* Keep the primary About and Contact CTAs on their dedicated pages. */
	if ( in_array( strtolower( $url ), array( '#about', strtolower( home_url( '/#about' ) ) ), true ) ) {
		return home_url( '/about-us/' );
	}
	if ( in_array( strtolower( $url ), array( '#contact', strtolower( home_url( '/#contact' ) ) ), true ) ) {
		return home_url( '/contact-us/' );
	}
	if ( in_array( strtolower( $url ), array( '#travel', strtolower( home_url( '/#travel' ) ) ), true ) ) {
		return home_url( '/travel-tourism/' );
	}
	if ( in_array( strtolower( $url ), array( '#real-estate', strtolower( home_url( '/#real-estate' ) ) ), true ) ) {
		return home_url( '/real-estate/' );
	}
	if ( in_array( strtolower( $url ), array( '#tea', strtolower( home_url( '/#tea' ) ) ), true ) ) {
		return home_url( '/tea-business/' );
	}
	if ( in_array( strtolower( $url ), array( '#properties', strtolower( home_url( '/#properties' ) ) ), true ) ) {
		return home_url( '/real-estate/' );
	}
	if ( in_array( strtolower( $url ), array( '#projects', strtolower( home_url( '/#projects' ) ) ), true ) ) {
		return home_url( '/projects/' );
	}
	if ( in_array( strtolower( $url ), array( '#open-positions', strtolower( home_url( '/#open-positions' ) ) ), true ) ) {
		return home_url( '/careers/#open-positions' );
	}
	if ( 0 === strpos( $url, '#' ) ) {
		return home_url( '/' . $url );
	}
	return $url;
}

